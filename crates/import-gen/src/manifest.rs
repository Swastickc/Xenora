//! Coverage manifest: collects classified records and renders reports.

use crate::classify::{Classification, SymbolDb};
use crate::parse::ImportRecord;
use std::collections::{BTreeMap, BTreeSet};

/// One classified import entry.
#[derive(Clone, Debug)]
pub struct ManifestEntry {
    pub module: String,
    pub symbol: String,
    pub ordinal: Option<u16>,
    pub iat_rva: u64,
    pub classification: Classification,
}

impl ManifestEntry {
    pub(crate) fn key(&self) -> (String, Option<u16>, &str) {
        (
            self.module.to_ascii_lowercase(),
            self.ordinal,
            if self.ordinal.is_none() {
                &self.symbol
            } else {
                ""
            },
        )
    }

    pub fn tier(&self) -> &'static str {
        self.classification.tier_name()
    }
    /// Runtime disposition of the generated output for this import.
    pub fn emission(&self) -> &'static str {
        match &self.classification {
            Classification::StandardService => "runtime-service",
            Classification::CrtNative { .. }
                if crate::codegen::crt_dispatch_expr(&self.symbol).is_some() =>
            {
                "generated-adapter"
            }
            Classification::CrtNative { .. }
            | Classification::CrtWrapper { .. }
            | Classification::RuntimeHelper { .. }
            | Classification::Win32Stub { .. } => "generated-stub",
            Classification::Manual { .. } | Classification::Unsupported { .. } => "no-binding",
        }
    }
}

/// Full coverage manifest for a set of import records.
pub struct Manifest {
    pub entries: Vec<ManifestEntry>,
}

impl Manifest {
    /// Classify every record using the symbol database.
    pub fn build(records: &[ImportRecord], db: &SymbolDb) -> Self {
        let mut entries = Vec::with_capacity(records.len());
        for rec in records {
            // Check for exact symbol match, then wildcard module match
            let classification = if rec.ordinal.is_some() {
                Classification::Manual {
                    reason: "ordinal requires a documented export mapping in the typed runtime registry",
                }
            } else if let Some(c) = db.get(&rec.module, &rec.symbol) {
                c.clone()
            } else if let Some(c) = db.get(&rec.module, "__wildcard__") {
                c.clone()
            } else {
                // Unknown — treat as Manual
                Classification::Manual {
                    reason: "no entry in built-in database — engineer required",
                }
            };
            entries.push(ManifestEntry {
                module: rec.module.clone(),
                symbol: rec.symbol.clone(),
                ordinal: rec.ordinal,
                iat_rva: rec.iat_rva,
                classification,
            });
        }
        Self { entries }
    }

    /// Count entries by tier.
    pub fn summary(&self) -> BTreeMap<&'static str, usize> {
        let mut m: BTreeMap<&'static str, usize> = BTreeMap::new();
        for e in &self.entries {
            *m.entry(e.tier()).or_default() += 1;
        }
        m
    }

    /// Count distinct module and symbol keys by emitted disposition.
    pub fn emission_summary(&self) -> BTreeMap<&'static str, usize> {
        let mut seen = BTreeSet::new();
        let mut counts = BTreeMap::new();
        for entry in &self.entries {
            if seen.insert(entry.key()) {
                *counts.entry(entry.emission()).or_default() += 1;
            }
        }
        counts
    }

    /// Entries that the generator can produce code for.
    pub fn generatable(&self) -> impl Iterator<Item = &ManifestEntry> {
        self.entries
            .iter()
            .filter(|e| e.classification.is_generatable())
    }

    /// Write the manifest as CSV for `xenora imports sync` integration.
    pub fn write_csv(&self, path: &str) -> Result<(), String> {
        let mut out = String::from("module,symbol,iat_rva,tier,emission,import_kind\n");
        for e in &self.entries {
            let kind = if e.ordinal.is_some() {
                "ordinal"
            } else {
                "name"
            };
            out.push_str(&format!(
                "\"{}\",\"{}\",0x{:08x},{},{},{kind}\n",
                e.module,
                e.symbol,
                e.iat_rva,
                e.tier(),
                e.emission()
            ));
        }
        std::fs::write(path, out).map_err(|e| format!("write manifest CSV {path}: {e}"))
    }

    /// Human-readable Markdown summary.
    pub fn render_markdown(&self) -> String {
        let summary = self.summary();
        let total = self.entries.len();
        let mut md = String::new();
        md.push_str("# Xenora import generator manifest\n\n");
        md.push_str("Generated by `xenora imports generate`. Do not edit manually.\n\n");
        md.push_str("## Catalog classification by import slot\n\n");
        md.push_str("| Tier | Count | % |\n| --- | ---: | ---: |\n");
        let total_pct = if total == 0 { 0 } else { 100 };
        md.push_str(&format!("| **Total** | {total} | {total_pct}% |\n"));
        for (tier, count) in &summary {
            let pct = (*count as f64 / total as f64 * 100.0) as u32;
            md.push_str(&format!("| `{tier}` | {count} | {pct}% |\n"));
        }
        md.push_str("\n## Emitted disposition by distinct import\n\n");
        md.push_str("| Disposition | Count |\n| --- | ---: |\n");
        let emissions = self.emission_summary();
        md.push_str(&format!(
            "| **Total** | {} |\n",
            emissions.values().sum::<usize>()
        ));
        for (disposition, count) in emissions {
            md.push_str(&format!("| `{disposition}` | {count} |\n"));
        }
        md.push_str("\nAdapters are emitted as partial handlers. Runtime services use existing registrations.\n");
        md.push_str("\n## Functions requiring manual engineering\n\n");
        for e in &self.entries {
            if let Classification::Manual { reason } | Classification::Unsupported { reason } =
                &e.classification
            {
                match crate::demangle(&e.symbol) {
                    Some(name) => md.push_str(&format!(
                        "- `{}!{}` (`{name}`) — {reason}\n",
                        e.module, e.symbol
                    )),
                    None => md.push_str(&format!("- `{}!{}` — {reason}\n", e.module, e.symbol)),
                }
            }
        }
        md
    }
}
